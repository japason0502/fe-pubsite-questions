function comboChoices(headers, rows) {
  const choices = rows.map((row, i) => ({
    id: IDS[i],
    text: row.join("，"),
  }));
  return { choices, choiceTable: { headers, rows } };
}

/** 1セル図表: 本文のみの table + 表外 caption（textCenter） */
function figureTableBlocks(caption, content) {
  return [
    { type: "table", headers: [""], rows: [[content]] },
    { type: "textCenter", text: caption },
  ];
}

